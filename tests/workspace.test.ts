import assert from 'node:assert/strict';
import {createId,preferences,descendantIds,folderRows,noteProblemIds,searchIndex,searchItems,elapsedSeconds,sameOutput,fileMetadataChangeAllowed,learningSuggestions} from '../lib/workspace.ts';
import {validateEntry} from '../lib/domain.ts';
let checks=0;const equal=(a:any,b:any)=>{assert.deepEqual(a,b);checks++;};
const entry=(id:string,kind:string,data:any,deleted=false)=>({id,kind,data,deleted,version:1,updated:'2026-10-23T01:00:00Z'}) as any;
const folders=[entry('a','folder',{title:'算法'}),entry('b','folder',{title:'二分',parentId:'a'}),entry('c','folder',{title:'边界',parentId:'b'}),entry('z','folder',{title:'孤立',parentId:'missing'})];
equal([...descendantIds(folders,'a')].sort(),['a','b','c']);
equal(folderRows(folders).find(f=>f.entry.id==='c')?.path,'算法 / 二分 / 边界');
equal(folderRows([...folders,entry('loop','folder',{title:'循环',parentId:'loop'})]).length,5);
equal(preferences({order:['notes','notes','bad'],hidden:['today','notes','bad'],sidebarWidth:900,fontSize:1}).order,['notes','today','problems','knowledge','review','records','studio']);
equal(preferences({hidden:['today','notes','bad']}).hidden,['notes']);
equal(preferences({sidebarWidth:900,fontSize:1}).sidebarWidth,320);
equal(preferences({fontSize:1}).fontSize,14);
equal(noteProblemIds({problemId:'P1',problemIds:['P1','P2','']}),['P1','P2']);
const index=searchIndex([{id:'p',code:'P1449',title:'后缀表达式',body:'stack pop'}],[{id:'d',kind:'STL专题',title:'stack',body:'P1449'}],[entry('n','note',{title:'我的笔记',body:'边界 STACK'}),entry('dead','note',{title:'STACK',body:''},true)]);
equal(searchItems(index,'Ｐ１４４９')[0].id,'p');
equal(searchItems(index,'stack 边界').map(i=>i.id),['n']);
equal(searchItems(index,'stack').some(i=>i.id==='dead'),false);
equal(searchItems(index,'  ').length,0);
equal(elapsedSeconds(10,1000,6000),15);
equal(elapsedSeconds(10,null,6000),10);
equal(elapsedSeconds(10,1000,0),10);
equal(sameOutput('1\n','1'),false);
equal(sameOutput('1\n','1\n'),true);
const file={key:'private/object',hash:'abc',size:3,name:'a.cpp',folderId:'a'};
equal(fileMetadataChangeAllowed(file,{...file,folderId:'b',title:'改名'}),true);
equal(fileMetadataChangeAllowed(file,{...file,key:'other/object'}),false);
equal(fileMetadataChangeAllowed(file,{...file,size:999}),false);
const ps=[{id:'p',title:'题1'},{id:'q',title:'题2'}];
const data=[entry('at','attempt',{problemId:'p',status:'进行中'}),entry('select','selection',{problemId:'q',day:'2026-10-23'})];
equal(learningSuggestions(ps,data,'2026-10-23',['p','q']).map(s=>s.problem.id),['p','q']);
equal(learningSuggestions(ps,[entry('deleted','attempt',{problemId:'p',status:'进行中'},true)],'2026-10-23',[]).length,0);
equal(validateEntry({id:'preferences:workspace',kind:'preference',data:preferences()}).kind,'preference');
assert.throws(()=>validateEntry({id:'preferences:other',kind:'preference',data:{order:'invalid'}}));checks++;
equal(createId({getRandomValues:(array:any)=>{array.fill(7);return array;}} as any),'07'.repeat(16));
console.log(`${checks} workspace assertions passed`);
