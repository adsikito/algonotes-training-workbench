import assert from 'node:assert/strict';
import {zipSync,strToU8} from 'fflate';
import {sha256} from '@noble/hashes/sha2.js';
import {checkBackupRecords} from '../lib/backup-limits.ts';
import {createBackup,previewRestore} from '../lib/backup-client.ts';
const bytes=strToU8('原件校验 hello'),digest=[...sha256(bytes)].map(n=>n.toString(16).padStart(2,'0')).join('');
const manifest={schemaVersion:1,snapshotId:'test',createdAt:'now',entries:[{id:'f1',kind:'file',data:{size:bytes.length,hash:digest,name:'a.txt'}},{id:'preferences:workspace',kind:'preference',data:{order:['today','notes'],pinnedNotes:['note-1']}},{id:'attempt-1',kind:'attempt',data:{tests:[{input:'2 3',expected:'5\n',actual:'5'}]}}],revisions:[]};
const originalFetch=globalThis.fetch;
globalThis.fetch=(async(url:any)=>String(url)==='/api/backup'?Response.json(manifest):new Response(bytes)) as any;
const out=await createBackup(()=>{});assert.equal(out.length,2);
const restored=await previewRestore(out.map(v=>new File([v.bytes as Uint8Array<ArrayBuffer>],v.name)));
assert.equal(restored.manifest.entries.length,3);assert.deepEqual(restored.bytes['files/f1'],bytes);
await assert.rejects(()=>previewRestore([new File([out[0].bytes as Uint8Array<ArrayBuffer>],'manifest.zip')]),/缺少附件/);
const bad=zipSync({'manifest.json':strToU8(JSON.stringify({...restored.manifest,files:[{id:'f1',path:'files/f1',hash:'bad'}]})),'files/f1':bytes});
await assert.rejects(()=>previewRestore([new File([bad],'bad.zip')]),/校验失败/);
assert.deepEqual(restored.manifest.entries[1].data.pinnedNotes,['note-1']);
assert.deepEqual(restored.manifest.entries[2].data.tests,[{input:'2 3',expected:'5\n',actual:'5'}]);
globalThis.fetch=originalFetch;
console.log('7 backup assertions passed: roundtrip, bytes, missing volume, corrupt hash');

checkBackupRecords({schemaVersion:1,entries:Array(3000).fill({}),revisions:Array(20000).fill({})});
assert.throws(()=>checkBackupRecords({schemaVersion:1,entries:Array(3001).fill({}),revisions:[]}),/3000/);
assert.throws(()=>checkBackupRecords({schemaVersion:1,entries:[],revisions:Array(20001).fill({})}),/20000/);
const mark={id:'mark1',kind:'bookmark',data:{targetId:'doc1',targetType:'document',markKind:'疑问',comment:'为什么',location:{line:3}}};
globalThis.fetch=(async()=>Response.json({...manifest,entries:[mark]})) as any;
const markBackup=await createBackup(()=>{});
assert.deepEqual((await previewRestore(markBackup.map(v=>new File([v.bytes as Uint8Array<ArrayBuffer>],v.name)))).manifest.entries[0],mark);
globalThis.fetch=originalFetch;
console.log('backup capacity boundaries and reading-mark roundtrip passed');
